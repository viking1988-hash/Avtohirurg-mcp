import os

from mcp.server.fastmcp import FastMCP

mcp = FastMCP(
    "Avtohirurg",
    host="0.0.0.0",
    port=int(os.environ.get("PORT", 8000)),
)

@mcp.tool()
def diagnose(service: str, audience: str) -> str:
    """
    Создаёт понятное описание услуги Автохирург
    для клиента с акцентом на диагностику и экономию.
    """

    benefit = (
        "Показываем, что именно неисправно, "
        "объясняем варианты ремонта и помогаем "
        "не тратить деньги на ненужную замену деталей."
    )

    return f"""
Автохирург — {service}.

Для {audience}, которым важно понимать,
за что они платят.

{benefit}

Запись — в Direct.
""".strip()
@mcp.tool()
def diagnose_symptom(symptom: str, car: str = "") -> str:
    """
    Анализирует жалобу клиента и формирует предварительный список
    возможных причин и необходимых проверок.
    """

    return f"""
Автохирург — предварительный анализ неисправности.

Автомобиль: {car if car else "не указан"}
Симптом клиента: {symptom}

Возможные причины:
1. Неисправность механического узла
2. Износ или повреждение детали
3. Нарушение работы электрической системы
4. Проблема с техническими жидкостями или их уровнем
5. Неисправность датчика или управляющей системы

Что проверить:
1. Визуально осмотреть узел
2. Проверить люфты, шумы и вибрации
3. Проверить технические жидкости
4. Выполнить компьютерную диагностику при необходимости
5. Провести проверку узла под нагрузкой
6. Зафиксировать найденную неисправность на фото

Важно:
Этот анализ является предварительным.
Не рекомендуется менять детали только по описанию симптома.
Сначала необходимо подтвердить неисправность диагностикой.

Главный принцип Автохирурга:
сначала найти и показать причину,
потом предлагать ремонт.
""".strip()
@mcp.tool()
def checklist() -> str:
    """
    Чек-лист диагностики автомобиля.
    """

    return """
Чек-лист Автохирург:

1. Визуальный осмотр
2. Проверка люфтов
3. Проверка технических жидкостей
4. Компьютерная диагностика
5. Проверка двигателя
6. Проверка турбокомпрессора
7. Проверка подвески
8. Проверка тормозной системы
9. Проверка рулевого управления
10. Проверка выхлопной системы
11. Определение срочности ремонта
12. Фотофиксация неисправности

Главный принцип:
сначала показать неисправность,
потом предложить ремонт.
""".strip()

if __name__ == "__main__":
    mcp.run(transport="streamable-http")
