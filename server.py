import os
from mcp.server.fastmcp import FastMCP

mcp = FastMCP("Avtohirurg", host="0.0.0.0", port=int(os.environ.get("PORT", 8000)))

AVTOHIRURG_RULES = """
ПРОТОКОЛ АВТОХИРУРГА
1. Не ставить окончательный диагноз только по жалобе.
2. Не утверждать неисправность детали без подтверждающей проверки.
3. Не придумывать проценты, цены, сроки или гарантию.
4. Отделять факты от предположений.
5. Сначала определить симптом и условия его появления.
6. Проверять от простого и безопасного к сложному.
7. При риске для безопасности рекомендовать прекратить эксплуатацию.
8. Не рекомендовать опасные проверки под автомобилем без оборудования.
9. Подтверждать неисправность измерением, тестом или доказательством.
10. Только после подтверждения предлагать ремонт.
Главный принцип: НЕ УГАДЫВАЕМ ДЕТАЛЬ. ДОКАЗЫВАЕМ НЕИСПРАВНОСТЬ.
""".strip()


def _log_tool(name: str, **data):
    details = " ".join(f"{k}={str(v)[:180]!r}" for k, v in data.items() if v not in (None, ""))
    print(f"[AVTOHIRURG_TOOL] {name}{(' ' + details) if details else ''}", flush=True)


def _critical():
    return [
        "не тормозит", "тормоза пропали", "педаль тормоза проваливается",
        "руль заклинивает", "руль не поворачивается", "рулевое управление отказало",
        "сильный люфт руля", "колесо болтается", "колесо отвал",
        "сильный перегрев", "температура в красной зоне", "лампа давления масла",
        "давление масла", "топливо течет", "топливо течёт",
        "сильная течь тормозной жидкости", "дым из-под капота", "сильный дым",
        "запах топлива", "металлический стук двигателя"
    ]


def _attention():
    return [
        "люфт", "вибрация", "стук", "хруст", "скрежет", "течь", "подтекает",
        "ошибка", "check engine", "необычный шум", "биение", "машину тянет",
        "тянет вправо", "тянет влево", "неравномерный износ"
    ]


def _safety(symptom: str) -> str:
    s = symptom.lower()
    if any(x in s for x in _critical()):
        return "🔴 ВЫСОКИЙ РИСК: до проверки эксплуатацию лучше прекратить."
    if any(x in s for x in _attention()):
        return "🟡 ТРЕБУЕТ ПРОВЕРКИ: избегать интенсивной эксплуатации до диагностики."
    return "🟢 По описанию критический риск не установлен; диагностика плановая, если нет других симптомов."


@mcp.tool()
def diagnose(service: str, audience: str) -> str:
    _log_tool("diagnose", service=service, audience=audience)
    return f"""Автохирург — {service}.
Для {audience}, которым важно понимать, за что они платят.
Показываем, что именно неисправно, объясняем варианты ремонта
и помогаем не тратить деньги на ненужную замену деталей.

{AVTOHIRURG_RULES}

Запись — в Direct.""".strip()


@mcp.tool()
def diagnose_symptom(symptom: str, car: str = "") -> str:
    _log_tool("diagnose_symptom", car=car, symptom=symptom)
    return f"""АВТОХИРУРГ — ПРЕДВАРИТЕЛЬНЫЙ АНАЛИЗ
Автомобиль: {car or 'не указан'}
Жалоба: {symptom}

ФАКТ: известен только описанный симптом. Конкретная деталь не подтверждена.

БЕЗОПАСНОСТЬ: {_safety(symptom)}

ПОРЯДОК:
1. Уточнить условия появления.
2. Локализовать источник.
3. Визуальный осмотр.
4. Проверить люфты, крепления и повреждения.
5. Выполнить измерения/компьютерную диагностику по показаниям.
6. Провести подтверждающий тест.
7. Зафиксировать фото/видео/измерение.
8. Только после подтверждения — ремонт.

{AVTOHIRURG_RULES}""".strip()


@mcp.tool()
def repair_urgency(symptom: str, car: str = "") -> str:
    _log_tool("repair_urgency", car=car, symptom=symptom)
    s = symptom.lower()
    if any(x in s for x in _critical()):
        level, action = "🔴 ВЫСОКАЯ СРОЧНОСТЬ", "Не продолжать движение до проверки."
    elif any(x in s for x in _attention()):
        level, action = "🟡 ТРЕБУЕТ ПРОВЕРКИ", "Ограничить эксплуатацию до диагностики."
    else:
        level, action = "🟢 ПЛАНОВАЯ ДИАГНОСТИКА", "Провести диагностику в плановом порядке."
    return f"""АВТОХИРУРГ — ОЦЕНКА СРОЧНОСТИ
Автомобиль: {car or 'не указан'}
Симптом: {symptom}

{level}
Что делать: {action}

Это предварительная оценка, а не диагноз.
{AVTOHIRURG_RULES}""".strip()


