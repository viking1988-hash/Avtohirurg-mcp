@mcp.tool()
def diagnostic_12_points(symptom: str, car: str = "") -> str:
    _log_tool("diagnostic_12_points", car=car, symptom=symptom)
    s = symptom.lower()

    priorities = []
    if any(x in s for x in ["тянет", "увод"]):
        priorities += [
            ("Высокий", "Шины и давление", "Давление по колёсам, типоразмер, износ, повреждения, шинный увод."),
            ("Высокий", "Тормоза", "Проверить возможное подклинивание и разницу работы левой/правой стороны."),
            ("Высокий", "Подвеска/рулевое", "Проверить люфты и изменение геометрии под нагрузкой."),
            ("Средний", "Сход-развал", "Измерить фактические углы после исключения механических причин.")
        ]
    if any(x in s for x in ["биение", "бьёт в руль", "бьет в руль"]):
        priorities += [
            ("Высокий", "Колёса и шины", "Проверить радиальное/осевое биение, балансировку и состояние дисков/шин."),
            ("Высокий", "Тормозная система", "Если биение возникает именно при торможении — сравнить состояние и работу передних тормозов."),
            ("Средний", "Ступицы", "Проверить биение/люфт ступицы после первичных проверок."),
            ("Средний", "Подвеска и рулевое", "Проверить люфты, крепления и изменение положения колеса.")
        ]
    if "стук" in s:
        priorities.append(("Высокий", "Локализация стука", "Воспроизвести на безопасном дорожном тесте и затем проверить соответствующие люфты."))
    if not priorities:
        priorities = [("Определяется после уточнения", "Условия симптома", "Сначала воспроизвести симптом и определить его условия появления.")]

    points = [
        ("1. Жалоба и условия", "Зафиксировать скорость, покрытие, разгон/торможение, поворот, холодный/горячий автомобиль.", "Симптом воспроизводится в тех же условиях."),
        ("2. Визуальный осмотр", "Осмотреть повреждения, течи, трещины, смещение и крепёж.", "Видимый дефект или отсутствие очевидного дефекта."),
        ("3. Жидкости", "Проверить уровни и следы утечек там, где они связаны с жалобой.", "Измеренный уровень/след течи или норма."),
        ("4. Люфты и крепления", "Проверить шарниры, сайлентблоки, ступицы и крепёж.", "Измеренный люфт или воспроизводимое перемещение."),
        ("5. Колёса и шины", "Проверить давление, износ, повреждения, биение и соответствие шин.", "Измерение и визуальное подтверждение."),
        ("6. Тормоза", "Проверить диски, колодки, суппорты, направляющие и равномерность работы.", "Измерение/осмотр и сравнение сторон."),
        ("7. Подвеска", "Проверить амортизаторы, пружины, рычаги, втулки и стабилизатор.", "Люфт, течь, повреждение или подтверждающий тест."),
        ("8. Рулевое", "Проверить тяги, наконечники, рейку и крепления.", "Измеренный люфт или подтверждающий тест."),
        ("9. Привод и агрегаты", "Проверить приводы, ШРУСы, подушки и связанные узлы, если симптом зависит от тяги/нагрузки.", "Осмотр, измерение или воспроизводимый тест."),
        ("10. Электроника", "Считать ошибки и параметры, если они могут объяснить симптом.", "Результат диагностического сканирования."),
        ("11. Подтверждающий тест", "Изменить один контролируемый фактор и повторить симптом; не менять несколько деталей одновременно.", "Причина подтверждается повторяемым изменением результата."),
        ("12. Доказательство и вывод", "Зафиксировать факт, проверку, результат, доказательство и решение по ремонту.", "Фото/видео/измерение/тест; только после этого — ремонт.")
    ]

    out = [
        "АВТОХИРУРГ — ДИАГНОСТИКА ПО 12 ПУНКТАМ",
        f"Автомобиль: {car or 'не указан'}",
        f"Симптом: {symptom}",
        "",
        f"БЕЗОПАСНОСТЬ: {_safety(symptom)}",
        "",
        "ФАКТЫ: известна только жалоба клиента.",
        "ПРЕДПОЛОЖЕНИЯ: перечисленные направления требуют проверки.",
        "",
        "ПРИОРИТЕТЫ"
    ]
    for level, area, check in priorities:
        out.append(f"[{level}] {area} — {check}")

    out += ["", "12 ПУНКТОВ"]
    for title, check, proof in points:
        out += [f"\n{title}", f"Что проверяем: {check}", f"Чем подтверждаем: {proof}"]

    out += [
        "",
        "РЕШЕНИЕ ПО РЕМОНТУ",
        "Ремонтировать сейчас: только неисправности, подтверждённые измерением, тестом или доказательством.",
        "Можно отложить: только то, что проверено и не создаёт установленного риска безопасности.",
        "Если дефект не подтверждён — деталь не приговаривать.",
        "",
        "ФАКТ → ПРОВЕРКА → РЕЗУЛЬТАТ → ДОКАЗАТЕЛЬСТВО → РЕШЕНИЕ",
        "",
        AVTOHIRURG_RULES
    ]
    return "\n".join(out)


