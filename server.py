def _safety(symptom: str) -> str:
    s = symptom.lower()
    if any(x in s for x in _critical()):
        return "🔴 ВЫСОКИЙ РИСК: до проверки эксплуатацию лучше прекратить."
    if any(x in s for x in [
        "перегрев двигателя", "двигатель перегревается",
        "температура растет", "температура растёт",
        "троит", "троение двигателя"
    ]):
        return "🔴 ПОВЫШЕННЫЙ РИСК: ограничить эксплуатацию до диагностики; при росте температуры, сильной тряске или других опасных признаках прекратить движение."
    if any(x in s for x in _attention()):
        return "🟡 ТРЕБУЕТ ПРОВЕРКИ: избегать интенсивной эксплуатации до диагностики."
    return "🟢 По описанию критический риск не установлен; диагностика плановая, если нет других симптомов."


def _carbone_key() -> str:
    return (
        os.environ.get("CARBONE_API_KEY")
        or os.environ.get("CARBONE_API_TOKEN")
        or os.environ.get("CARBONE_TOKEN")
        or ""
    ).strip()


def _carbone_pdf(template_html: str, data: dict[str, Any], report_name: str) -> bytes:
    token = _carbone_key()
    if not token:
        raise RuntimeError("Не найден ключ Carbone. Укажи CARBONE_API_KEY в Railway Variables.")

    payload = {
        "template": base64.b64encode(template_html.encode("utf-8")).decode("ascii"),
        "data": data,
        "convertTo": "pdf",
        "reportName": report_name,
    }
    req = urllib.request.Request(
        "https://api.carbone.io/render/template?download=true",
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Accept": "application/pdf",
            "User-Agent": "Avtohirurg-MCP/1.0",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            content = response.read()
            content_type = response.headers.get("Content-Type", "")
            if "application/pdf" not in content_type.lower() and not content.startswith(b"%PDF"):
                try:
                    body = content.decode("utf-8", errors="replace")[:1000]
                except Exception:
                    body = "Carbone returned a non-PDF response."
                raise RuntimeError(f"Carbone не вернул PDF: {body}")
            return content
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")[:1500]
        raise RuntimeError(f"Carbone HTTP {exc.code}: {body}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Не удалось подключиться к Carbone: {exc.reason}") from exc


def _pdf_resource(pdf: bytes, filename: str) -> EmbeddedResource:
    return EmbeddedResource(
        resource=BlobResourceContents(
            uri=f"urn:avtohirurg:{filename}",
            mimeType="application/pdf",
            blob=base64.b64encode(pdf).decode("ascii"),
        )
    )


