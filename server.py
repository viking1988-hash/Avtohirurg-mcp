@mcp.tool()
def repair_urgency(symptom: str, car: str = "") -> str:
    _log_tool("repair_urgency", car=car, symptom=symptom)
    s = symptom.lower()
    if any(x in s for x in _critical()):
        level, action = "🔴 ВЫСОКАЯ СРОЧНОСТЬ", "Не продолжать движение до проверки."
    elif any(x in s for x in ["перегрев двигателя", "двигатель перегревается", "троит", "троение двигателя"]):
        level, action = "🔴 ПОВЫШЕННАЯ СРОЧНОСТЬ", "Ограничить эксплуатацию; при росте температуры или сильной тряске прекратить движение и провести диагностику."
    elif any(x in s for x in _attention()):
        level, action = "🟡 ТРЕБУЕТ ПРОВЕРКИ", "Ограничить интенсивную эксплуатацию до диагностики."
    else:
        level, action = "🟢 ПЛАНОВАЯ ДИАГНОСТИКА", "Провести диагностику в плановом порядке."
    return f"""АВТОХИРУРГ — ОЦЕНКА СРОЧНОСТИ
Автомобиль: {car or 'не указан'}
Симптом: {symptom}

{level}
Что делать: {action}

Это предварительная оценка, а не диагноз.
{AVTOHIRURG_RULES}""".strip()


