def _log_tool(name: str, **data):
    details = " ".join(
        f"{k}={str(v)[:180]!r}" for k, v in data.items() if v not in (None, "")
    )
    print(f"[AVTOHIRURG_TOOL] {name}{(' ' + details) if details else ''}", flush=True)


