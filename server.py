import os

from mcp.server.fastmcp import FastMCP


mcp = FastMCP(
    "Avtohirurg",
    host="0.0.0.0",
    port=int(os.environ.get("PORT", 8000)),
)


AVTOHIRURG_RULES = """
ПРОТОКОЛ АВТОХИРУРГА

1. Не ставить окончательный диагноз только по жалобе клиента.
2. Не утверждать неисправность конкретной детали без подтверждающей проверки.
3. Не придумывать проценты вероятности, цены, сроки ремонта или гарантию.
4. Отделять факты от предположений.
5. Сначала определить симптом и условия его появления.
6. Затем предложить последовательность проверки от простого к сложному.
7. Если безопасность может быть нарушена, рекомендовать безопасно прекратить эксплуатацию до проверки.
8. Не рекомендовать клиенту опасные самостоятельные проверки под автомобилем без подходящего оборудования и опыта.
9. После обнаружения неисправности подтвердить её измерением, тестом или визуальным доказательством, когда это возможно.
10. Только после подтверждения предлагать ремонт.

Главный принцип:
НЕ УГАДЫВАЕМ ДЕТАЛЬ. ДОКАЗЫВАЕМ НЕИСПРАВНОСТЬ.
""".strip()


@mcp.tool()
def diagnose(service: str, audience: str) -> str:
    """Создаёт понятное описание услуги Автохирург для клиента."""

    return f"""
Автохирург — {service}.

Для {audience}, которым важно понимать, за что они платят.

Показываем, что именно неисправно, объясняем варианты ремонта
и помогаем не тратить деньги на ненужную замену деталей.

{AVTOHIRURG_RULES}

Запись — в Direct.
""".strip()


@mcp.tool()
def diagnose_symptom(symptom: str, car: str = "") -> str:
    """Проводит предварительный анализ симптома без постановки окончательного диагноза."""

    symptom_lower = symptom.lower()

    critical_signs = [
        "не тормозит",
        "тормоза пропали",
        "педаль тормоза проваливается",
        "руль заклинивает",
        "руль не поворачивается",
        "рулевое управление отказало",
        "сильный люфт руля",
        "колесо болтается",
        "колесо отвал",
        "сильный перегрев",
        "температура в красной зоне",
        "лампа давления масла",
        "давление масла",
        "топливо течет",
        "топливо течёт",
        "сильная течь тормозной жидкости",
        "дым из-под капота",
        "сильный дым",
        "запах топлива",
        "металлический стук двигателя",
    ]

    critical = any(word in symptom_lower for word in critical_signs)

    if critical:
        urgency = (
            "ВЫСОКАЯ ОСТОРОЖНОСТЬ: описан потенциально опасный признак. "
            "До проверки не рекомендуется продолжать движение своим ходом. "
            "При необходимости используйте безопасный способ доставки автомобиля в сервис."
        )
    else:
        urgency = (
            "Срочность нельзя достоверно определить только по описанию симптома. "
            "Сначала необходимо установить источник и состояние узла."
        )

    return f"""
АВТОХИРУРГ — ПРЕДВАРИТЕЛЬНЫЙ АНАЛИЗ СИМПТОМА

Автомобиль:
{car if car else "не указан"}

Жалоба клиента:
{symptom}

ЧТО ИЗВЕСТНО

У нас есть только описание симптома.
Конкретная неисправная деталь пока НЕ подтверждена.

ВОЗМОЖНЫЕ НАПРАВЛЕНИЯ

- механический износ или люфт;
- повреждение креплений, пыльников или соединений;
- проблемы со смазкой или загрязнением;
- неисправность электрического компонента или датчика;
- другой узел может создавать похожий симптом.

ПОРЯДОК ДИАГНОСТИКИ

1. Уточнить, когда появляется симптом:
   на месте, при движении, на холодную, после прогрева,
   при разгоне, торможении, повороте или на неровностях.

2. Определить максимально точное место возникновения.

3. Выполнить визуальный осмотр.

4. Проверить люфты, крепления, пыльники и состояние доступных узлов.

5. Выполнить необходимые измерения или компьютерную диагностику.

6. Подтвердить найденную неисправность тестом или измерением,
   когда это возможно.

7. Зафиксировать обнаруженную неисправность фото или видео.

8. Только после подтверждения обсуждать ремонт.

ЧТО УТОЧНИТЬ

- марка, модель и год;
- двигатель и коробка передач;
- когда появился симптом;
- при каких условиях возникает;
- с какой стороны или из какой области слышен звук;
- меняется ли он со скоростью или оборотами;
- был ли недавний ремонт;
- есть ли предупреждения или ошибки на панели.

ОЦЕНКА БЕЗОПАСНОСТИ

{urgency}

САМОСТОЯТЕЛЬНАЯ ПРОВЕРКА

Не выполнять работы под автомобилем только на одном домкрате.
Если нет подходящего оборудования и опыта, проверку должен выполнить специалист.

{AVTOHIRURG_RULES}
""".strip()


@mcp.tool()
def repair_urgency(symptom: str, car: str = "") -> str:
    """Оценивает предварительную срочность по описанию симптома."""

    symptom_lower = symptom.lower()

    critical_signs = [
        "не тормозит",
        "тормоза пропали",
        "педаль тормоза проваливается",
        "руль заклинивает",
        "руль не поворачивается",
        "рулевое управление отказало",
        "сильный люфт руля",
        "колесо болтается",
        "колесо отвал",
        "сильный перегрев",
        "температура в красной зоне",
        "лампа давления масла",
        "давление масла",
        "топливо течет",
        "топливо течёт",
        "сильная течь тормозной жидкости",
        "дым из-под капота",
        "сильный дым",
        "запах топлива",
        "металлический стук двигателя",
    ]

    attention_signs = [
        "люфт",
        "вибрация",
        "стук",
        "хруст",
        "скрежет",
        "течь",
        "подтекает",
        "ошибка",
        "check engine",
        "необычный шум",
        "биение",
        "машину тянет",
        "неравномерный износ",
    ]

    critical = any(word in symptom_lower for word in critical_signs)
    attention = any(word in symptom_lower for word in attention_signs)

    if critical:
        level = "🔴 ВЫСОКАЯ СРОЧНОСТЬ"
        recommendation = (
            "Не рекомендуется продолжать движение до проверки автомобиля. "
            "При необходимости автомобиль лучше доставить в сервис безопасным способом."
        )
        reason = (
            "В описании присутствует потенциально опасный признак, "
            "связанный с критически важной системой или риском повреждения автомобиля."
        )

    elif attention:
        level = "🟡 ТРЕБУЕТ ПРОВЕРКИ"
        recommendation = (
            "Желательно ограничить эксплуатацию до диагностики "
            "и установить источник симптома."
        )
        reason = (
            "Есть признак, требующий проверки, но его тяжесть "
            "нельзя определить без осмотра."
        )

    else:
        level = "🟢 ПЛАНОВАЯ ДИАГНОСТИКА"
        recommendation = (
            "Явных критических признаков в описании нет, "
            "однако неисправность желательно диагностировать."
        )
        reason = (
            "По описанию нет признака непосредственной угрозы, "
            "но отсутствие такого признака не подтверждает исправность автомобиля."
        )

    return f"""
АВТОХИРУРГ — ОЦЕНКА СРОЧНОСТИ

Автомобиль:
{car if car else "не указан"}

Симптом:
{symptom}

ОЦЕНКА:
{level}

ПОЧЕМУ:
{reason}

ЧТО ДЕЛАТЬ:
{recommendation}

ВАЖНО:

Это предварительная оценка, а не подтверждение исправности
или неисправности конкретного узла.

{AVTOHIRURG_RULES}
""".strip()


@mcp.tool()
def avtohirurg_protocol(
    symptom: str,
    car: str = "",
    diagnostic_results: str = "",
) -> str:
    """Формирует единый структурированный протокол Автохирурга."""

    results = (
        diagnostic_results.strip()
        if diagnostic_results.strip()
        else "Результаты диагностики пока не предоставлены."
    )

    return f"""
АВТОХИРУРГ — ЕДИНЫЙ ПРОТОКОЛ ДИАГНОСТИКИ

АВТОМОБИЛЬ:
{car if car else "не указан"}

СИМПТОМ / ЖАЛОБА:
{symptom}

РЕЗУЛЬТАТЫ ДИАГНОСТИКИ:
{results}

1. ФАКТЫ

Отделить то, что сообщил клиент или показала проверка,
от предположений.

2. ЧТО ПОКА НЕ ДОКАЗАНО

Не объявлять конкретную деталь неисправной без подтверждения.

3. ВОЗМОЖНЫЕ НАПРАВЛЕНИЯ

Составить только те направления, которые логично связаны
с симптомом и условиями его появления.

4. ПОРЯДОК ПРОВЕРКИ

Начать с безопасных и информативных проверок,
затем переходить к более сложным.

5. ПОДТВЕРЖДЕНИЕ

Для каждой предполагаемой неисправности указать,
чем её можно подтвердить: визуально, измерением,
люфтом, тестом, диагностическим оборудованием
или другой проверкой.

6. СРОЧНОСТЬ

Если есть признаки потенциальной опасности для тормозов,
рулевого управления, колёс, перегрева, давления масла
или утечки топлива — рекомендовать безопасно прекратить
эксплуатацию до проверки.

7. РЕКОМЕНДАЦИЯ КЛИЕНТУ

Объяснить простыми словами, что делать дальше и почему.

8. РЕШЕНИЕ О РЕМОНТЕ

Ремонт предлагается только после подтверждения неисправности.

9. ДОКАЗАТЕЛЬСТВО

По возможности показать клиенту найденный дефект,
измерение, люфт, повреждение или результат теста.

ЗАПРЕЩЕНО:

- выдумывать проценты вероятности;
- выдумывать цены и сроки ремонта;
- утверждать диагноз без проверки;
- обещать безопасность эксплуатации без достаточных данных;
- рекомендовать замену детали только «на всякий случай».

{AVTOHIRURG_RULES}
""".strip()


@mcp.tool()
def checklist() -> str:
    """Чек-лист диагностики автомобиля."""

    return """
ЧЕК-ЛИСТ АВТОХИРУРГА

1. Визуальный осмотр
2. Проверка люфтов
3. Проверка технических жидкостей
4. Компьютерная диагностика при необходимости
5. Проверка двигателя
6. Проверка турбокомпрессора
7. Проверка подвески
8. Проверка тормозной системы
9. Проверка рулевого управления
10. Проверка выхлопной системы
11. Определение срочности ремонта
12. Фотофиксация неисправности

Главный принцип:

сначала найти и показать неисправность,
потом предложить ремонт.
""".strip()


