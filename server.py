@mcp.tool()
def generate_test_document(car: str = "Toyota Camry 2015", symptom: str = "Тест Carbone", status: str = "OK") -> EmbeddedResource:
    """Создаёт тестовый PDF через Carbone и возвращает PDF прямо внутри MCP-ответа.

    Это специально сделано без выдачи временной R2/S3-ссылки, чтобы подпись URL
    не ломалась из-за трекинга ссылок.
    """
    _log_tool("generate_test_document", car=car, symptom=symptom, status=status)
    template = """<!doctype html><html><head><meta charset='utf-8'><style>body{font-family:Arial,sans-serif;margin:40px}h1{font-size:24px}p{font-size:14px;line-height:1.5}.ok{font-weight:bold}</style></head><body><h1>Автохирург — ТЕСТ CARBONE</h1><p>Документ успешно создан через Carbone.</p><p><b>Автомобиль:</b> {d.car}</p><p><b>Симптом:</b> {d.symptom}</p><p class='ok'><b>Статус:</b> {d.status}</p><p>Поток: Автохирург MCP → Carbone → PDF → MCP.</p></body></html>"""
    pdf = _carbone_pdf(template, {"car": car, "symptom": symptom, "status": status}, "avtohirurg-test.pdf")
    return _pdf_resource(pdf, "avtohirurg-test.pdf")


@mcp.tool()
def generate_diagnostic_pdf(car: str, symptom: str) -> EmbeddedResource:
    """Формирует PDF с диагностическим протоколом Автохирурга по 12 пунктам через Carbone."""
    _log_tool("generate_diagnostic_pdf", car=car, symptom=symptom)
    diagnostic = diagnostic_12_points(symptom=symptom, car=car)
    safe_diag = diagnostic.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br>")
    template = """<!doctype html><html><head><meta charset='utf-8'><style>body{font-family:Arial,sans-serif;margin:32px}h1{font-size:22px}h2{font-size:16px;margin-top:20px}.meta{padding:10px;border:1px solid #ddd}.diag{font-size:11px;line-height:1.45;white-space:normal}</style></head><body><h1>Автохирург — диагностический протокол</h1><div class='meta'><b>Автомобиль:</b> {d.car}<br><b>Симптом:</b> {d.symptom}</div><h2>Протокол 12 пунктов</h2><div class='diag'>{d.diagnostic}</div></body></html>"""
    pdf = _carbone_pdf(template, {"car": car, "symptom": symptom, "diagnostic": safe_diag}, "avtohirurg-diagnostic.pdf")
    return _pdf_resource(pdf, "avtohirurg-diagnostic.pdf")


