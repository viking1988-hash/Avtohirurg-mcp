import os

from mcp.server.fastmcp import FastMCP

mcp = FastMCP(
    "Avtohirurg",
    host="0.0.0.0",
    port=int(os.environ.get("PORT", 8000)),
)

@mcp.tool()
def diagnose(service: str, audience: str) -> str:
    """
    Создаёт понятное описание услуги Автохирург
    для клиента с акцентом на диагностику и экономию.
    """

    benefit = (
        "Показываем, что именно неисправно, "
        "объясняем варианты ремонта и помогаем "
        "не тратить деньги на ненужную замену деталей."
    )

    return f"""
Автохирург — {service}.

Для {audience}, которым важно понимать,
за что они платят.

{benefit}

Запись — в Direct.
""".strip()
@mcp.tool()
def diagnose_symptom(symptom: str, car: str = "") -> str:
    """
    Проводит предварительный анализ симптома автомобиля
    по принципам диагностики Автохирурга.

    Важно:
    - не ставит окончательный диагноз по одному симптому;
    - не придумывает вероятность неисправности;
    - разделяет возможные причины и подтвержденные неисправности;
    - определяет срочность;
    - предлагает последовательность проверок.
    """

    symptom_lower = symptom.lower()

    urgent_keywords = [
        "тормоз", "не тормозит", "руль", "рулев", "масло течет",
        "масло течёт", "перегрев", "температура", "дым", "запах бензина",
        "топливо течет", "топливо течёт", "стучит двигатель",
        "лампа масла", "давление масла"
    ]

    urgent = any(word in symptom_lower for word in urgent_keywords)

    if urgent:
        urgency = (
            "ПОВЫШЕННАЯ ВНИМАТЕЛЬНОСТЬ: до проверки автомобиля "
            "не рекомендуется продолжать эксплуатацию, если симптом "
            "связан с тормозами, рулевым управлением, перегревом, "
            "давлением масла, утечкой топлива или сильным дымом."
        )
    else:
        urgency = (
            "Срочность нельзя определить только по описанию симптома. "
            "Сначала необходимо установить причину и оценить состояние узла."
        )

    return f"""
АВТОХИРУРГ — ПРЕДВАРИТЕЛЬНЫЙ АНАЛИЗ СИМПТОМА

Автомобиль:
{car if car else "не указан"}

Жалоба клиента:
{symptom}

ВАЖНО
По одному симптому нельзя объявлять конкретную деталь неисправной.
Ниже перечислены возможные направления диагностики, а не окончательный диагноз.

ВОЗМОЖНЫЕ ПРИЧИНЫ

1. Механический износ или люфт деталей.
2. Повреждение креплений, пыльников или соединений.
3. Недостаток смазки либо загрязнение узла.
4. Неисправность электрического компонента или датчика.
5. Нарушение работы другого узла, которое проявляется похожим симптомом.

АЛГОРИТМ АВТОХИРУРГА

1. Уточнить, когда появляется симптом:
   - на месте;
   - при движении;
   - на холодную;
   - после прогрева;
   - при разгоне;
   - при торможении;
   - при повороте;
   - на неровностях.

2. Определить точное место возникновения звука,
   вибрации, запаха или другого проявления.

3. Выполнить визуальный осмотр.

4. Проверить люфты, крепления, пыльники и механическое состояние узлов.

5. Выполнить необходимые измерения или компьютерную диагностику.

6. При возможности подтвердить неисправность нагрузочным тестом.

7. Сделать фото или видео найденной неисправности.

8. Только после подтверждения предложить ремонт.

ЧТО НУЖНО УТОЧНИТЬ У КЛИЕНТА

- Марка, модель и год автомобиля.
- Двигатель и коробка передач.
- Когда появился симптом.
- При каких условиях он возникает.
- С какой стороны или из какой области слышен звук.
- Меняется ли симптом при изменении скорости или оборотов.
- Были ли недавно ремонт или замена деталей.
- Есть ли предупреждения или ошибки на приборной панели.

ОЦЕНКА СРОЧНОСТИ

{urgency}

ПРИНЦИП АВТОХИРУРГА

Не приговариваем деталь по одному симптому.

Сначала:
НАЙТИ → ПРОВЕРИТЬ → ПОКАЗАТЬ НЕИСПРАВНОСТЬ

И только потом:
ПРЕДЛОЖИТЬ РЕМОНТ.

Не рекомендуется менять дорогую деталь только потому,
что её неисправность предположили по характерному симптому.
""".strip()
@mcp.tool()
def checklist() -> str:
    """
    Чек-лист диагностики автомобиля.
    """

    return """
Чек-лист Автохирург:

1. Визуальный осмотр
2. Проверка люфтов
3. Проверка технических жидкостей
4. Компьютерная диагностика
5. Проверка двигателя
6. Проверка турбокомпрессора
7. Проверка подвески
8. Проверка тормозной системы
9. Проверка рулевого управления
10. Проверка выхлопной системы
11. Определение срочности ремонта
12. Фотофиксация неисправности

Главный принцип:
сначала показать неисправность,
потом предложить ремонт.
""".strip()

if __name__ == "__main__":
    mcp.run(transport="streamable-http")
